static int ensure_dir(const char *path)
{
    return vigil_platform_mkdir_p(path, NULL) == VIGIL_STATUS_OK;
}

static vigil_editor_result_t install_vim_family(const char *editor_name, const char *root)
{
    char ft_path[1024], syn_path[1024], dir[1024];
    if (!pjoin(dir, sizeof(dir), root, "after") || !pjoin(dir, sizeof(dir), dir, "ftdetect"))
        return result_err("path too long");
    if (!ensure_dir(dir))
        return result_err("failed to create filetype directory");
    if (!pjoin(ft_path, sizeof(ft_path), dir, "vigil.vim"))
        return result_err("path too long");

    if (!pjoin(dir, sizeof(dir), root, "after") || !pjoin(dir, sizeof(dir), dir, "syntax"))
        return result_err("path too long");
    if (!ensure_dir(dir))
        return result_err("failed to create syntax directory");
    if (!pjoin(syn_path, sizeof(syn_path), dir, "vigil.vim"))
        return result_err("path too long");

    printf("Creating %s\n", ft_path);
    if (!pwrite(ft_path, vim_ft_content))
        return result_err("failed to write filetype config");
    printf("Creating %s\n", syn_path);
    if (!pwrite(syn_path, vim_syn_content))
        return result_err("failed to write syntax config");

    {
        char message[256];
        snprintf(message, sizeof(message), "Done. To undo: vigil editor uninstall %s", editor_name);
        return result_ok(message);
    }
}

static vigil_editor_result_t uninstall_vim_family(const char *root)
{
    char path[1024], dir[1024];
    if (pjoin(dir, sizeof(dir), root, "after"))
    {
        char sub[1024];
        if (pjoin(sub, sizeof(sub), dir, "ftdetect") && pjoin(path, sizeof(path), sub, "vigil.vim"))
            premove(path);
        if (pjoin(sub, sizeof(sub), dir, "syntax") && pjoin(path, sizeof(path), sub, "vigil.vim"))
            premove(path);
    }
    return result_ok("Done.");
}

static int is_installed_vim_family(const char *root)
{
    char path[1024], dir[1024];
    if (!pjoin(dir, sizeof(dir), root, "after") || !pjoin(dir, sizeof(dir), dir, "ftdetect") ||
        !pjoin(path, sizeof(path), dir, "vigil.vim"))
        return 0;
    return pexists(path);
}

