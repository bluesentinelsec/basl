static int vscode_ext_dir(char *buf, size_t cap, const char *home)
{
    return pjoin(buf, cap, home, ".vscode") && pjoin(buf, cap, buf, "extensions") && pjoin(buf, cap, buf, "vigil-lang");
}

static vigil_editor_result_t install_vscode(const char *vigil_bin, const char *home)
{
    char ext_dir[1024], path[1024], content[2048];

    if (!vscode_ext_dir(ext_dir, sizeof(ext_dir), home))
        return result_err("path too long");
    vigil_platform_mkdir_p(ext_dir, NULL);

    if (!pjoin(path, sizeof(path), ext_dir, "package.json"))
        return result_err("path too long");
    vscode_pkg_content(content, sizeof(content));
    printf("Creating %s\n", path);
    if (!pwrite(path, content))
        return result_err("failed to write package.json");

    if (!pjoin(path, sizeof(path), ext_dir, "extension.js"))
        return result_err("path too long");
    vscode_ext_content(content, sizeof(content), vigil_bin);
    printf("Creating %s\n", path);
    if (!pwrite(path, content))
        return result_err("failed to write extension.js");

    if (!pjoin(path, sizeof(path), ext_dir, "language-configuration.json"))
        return result_err("path too long");
    printf("Creating %s\n", path);
    if (!pwrite(path, vscode_langconf))
    {
        return result_err("failed to write language config");
    }

    /* Install npm dependencies (not available on iOS/Android/Emscripten) */
#if !defined(__EMSCRIPTEN__) && !defined(__ANDROID__) && !(defined(__APPLE__) && TARGET_OS_IPHONE)
    printf("Running npm install in %s\n", ext_dir);
    {
        char cmd[1200];
#ifdef _WIN32
        snprintf(cmd, sizeof(cmd), "cd /d \"%s\" && npm install --silent 2>nul", ext_dir);
#else
        snprintf(cmd, sizeof(cmd), "cd \"%s\" && npm install --silent 2>&1", ext_dir);
#endif
        int rc = system(cmd);
        if (rc != 0)
            return result_err("npm install failed - is Node.js installed?");
    }
#endif

    return result_ok("Done. Reload VS Code and open a .vigil file.\n"
                     "To undo: vigil editor uninstall vscode");
}

static vigil_editor_result_t uninstall_vscode(const char *home)
{
    char ext_dir[1024], path[1024];
    if (!vscode_ext_dir(ext_dir, sizeof(ext_dir), home))
        return result_ok("Done.");

    const char *files[] = {"package.json", "extension.js", "language-configuration.json", "package-lock.json", NULL};
    for (const char *const *f = files; *f; f++)
    {
        if (pjoin(path, sizeof(path), ext_dir, *f))
            premove(path);
    }
    /* Remove node_modules */
    if (pjoin(path, sizeof(path), ext_dir, "node_modules"))
    {
        printf("Removing %s\n", path);
        vigil_platform_remove_all(path, NULL);
    }
    return result_ok("Done.");
}

static int is_installed_vscode(const char *home)
{
    char path[1024], ext_dir[1024];
    if (!vscode_ext_dir(ext_dir, sizeof(ext_dir), home))
        return 0;
    if (!pjoin(path, sizeof(path), ext_dir, "package.json"))
        return 0;
    return pexists(path);
}

/* ── emacs ───────────────────────────────────────────────────────── */

static const char emacs_marker_begin[] = ";; BEGIN vigil editor integration\n";
static const char emacs_marker_end[] = ";; END vigil editor integration\n";

static int emacs_escape_string(const char *input, char *out, size_t cap)
{
    size_t i;
    size_t j = 0;
    for (i = 0; input[i] != '\0'; i++)
    {
        if (j + 2 >= cap)
            return 0;
        if (input[i] == '\\' || input[i] == '"')
            out[j++] = '\\';
        out[j++] = input[i];
    }
    if (j >= cap)
        return 0;
    out[j] = '\0';
    return 1;
}

static int emacs_init_path(char *buf, size_t cap, const char *home)
{
    char dir[1024];
    if (!emacs_dir(dir, sizeof(dir), home))
        return 0;
    return pjoin(buf, cap, dir, "init.el");
}

static int emacs_mode_path(char *buf, size_t cap, const char *home)
{
    char dir[1024];
    if (!emacs_dir(dir, sizeof(dir), home))
        return 0;
    return pjoin(buf, cap, dir, "vigil-mode.el");
}

static int emacs_init_block(char *buf, size_t cap, const char *mode_path)
{
    char escaped[2048];
    if (!emacs_escape_string(mode_path, escaped, sizeof(escaped)))
        return 0;
    snprintf(buf, cap,
             "%s"
             "(load-file \"%s\")\n"
             "(add-to-list 'auto-mode-alist '(\"\\\\.vigil\\\\'\" . vigil-mode))\n"
             "%s",
             emacs_marker_begin, escaped, emacs_marker_end);
    return 1;
}

static int emacs_write_init_with_block(const char *init_path, const char *existing, size_t existing_length,
                                       const char *block)
{
    size_t block_length = strlen(block);
    size_t needs_newline = 0;
    size_t out_length;
    char *out;

    if (existing && strstr(existing, emacs_marker_begin) != NULL)
        return 1;
    if (existing_length > 0 && existing[existing_length - 1] != '\n')
        needs_newline = 1;
    out_length = existing_length + needs_newline + block_length;
    out = (char *)malloc(out_length + 1);
    if (!out)
        return 0;
    if (existing_length > 0)
        memcpy(out, existing, existing_length);
    if (needs_newline)
        out[existing_length] = '\n';
    memcpy(out + existing_length + needs_newline, block, block_length);
    out[out_length] = '\0';

    if (!pwrite_len(init_path, out, out_length))
    {
        free(out);
        return 0;
    }
    free(out);
    return 1;
}

static vigil_editor_result_t install_emacs(const char *vigil_bin, const char *home)
{
    char dir[1024], init_path[1024], mode_path[1024], block[3072];
    char *init_content = NULL;
    size_t init_length = 0;
    (void)vigil_bin;

    if (!emacs_dir(dir, sizeof(dir), home) || !emacs_init_path(init_path, sizeof(init_path), home) ||
        !emacs_mode_path(mode_path, sizeof(mode_path), home))
        return result_err("path too long");
    if (!ensure_dir(dir))
        return result_err("failed to create emacs config directory");

    printf("Creating %s\n", mode_path);
    if (!pwrite(mode_path, emacs_mode_content))
        return result_err("failed to write emacs mode");
    if (!emacs_init_block(block, sizeof(block), mode_path))
        return result_err("failed to build emacs init block");

    if (pread(init_path, &init_content, &init_length))
    {
        if (!emacs_write_init_with_block(init_path, init_content, init_length, block))
        {
            free(init_content);
            return result_err("failed to update init.el");
        }
        free(init_content);
    }
    else
    {
        printf("Creating %s\n", init_path);
        if (!pwrite(init_path, block))
            return result_err("failed to write init.el");
    }

    return result_ok("Done. Restart Emacs or reload init.el.\nTo undo: vigil editor uninstall emacs");
}

static vigil_editor_result_t uninstall_emacs(const char *home)
{
    char init_path[1024], mode_path[1024];
    char *init_content = NULL;
    size_t init_length = 0;
    char *begin;
    char *end;

    if (!emacs_init_path(init_path, sizeof(init_path), home) || !emacs_mode_path(mode_path, sizeof(mode_path), home))
        return result_ok("Done.");

    premove(mode_path);

    if (!pread(init_path, &init_content, &init_length))
        return result_ok("Done.");

    begin = strstr(init_content, emacs_marker_begin);
    end = strstr(init_content, emacs_marker_end);
    if (begin && end && end >= begin)
    {
        size_t prefix_len = (size_t)(begin - init_content);
        size_t suffix_offset = (size_t)(end - init_content) + strlen(emacs_marker_end);
        size_t suffix_len = init_length - suffix_offset;
        memmove(begin, init_content + suffix_offset, suffix_len);
        init_length = prefix_len + suffix_len;
        if (!pwrite_len(init_path, init_content, init_length))
        {
            free(init_content);
            return result_err("failed to update init.el");
        }
    }
    free(init_content);
    return result_ok("Done.");
}

static int is_installed_emacs(const char *home)
{
    char mode_path[1024];
    if (!emacs_mode_path(mode_path, sizeof(mode_path), home))
        return 0;
    return pexists(mode_path);
}

