/* ── path helpers using platform layer ───────────────────────────── */

static int pjoin(char *buf, size_t cap, const char *a, const char *b)
{
    return vigil_platform_path_join(a, b, buf, cap, NULL) == VIGIL_STATUS_OK;
}

static int pexists(const char *path)
{
    int exists = 0;
    vigil_platform_file_exists(path, &exists);
    return exists;
}

static int pwrite(const char *path, const char *content)
{
    return vigil_platform_write_file(path, content, strlen(content), NULL) == VIGIL_STATUS_OK;
}

static int pwrite_len(const char *path, const char *content, size_t length)
{
    return vigil_platform_write_file(path, content, length, NULL) == VIGIL_STATUS_OK;
}

static int pread(const char *path, char **out_content, size_t *out_length)
{
    char *content = NULL;
    size_t length = 0;
    if (vigil_platform_read_file(NULL, path, &content, &length, NULL) != VIGIL_STATUS_OK)
        return 0;
    *out_content = content;
    *out_length = length;
    return 1;
}

static void premove(const char *path)
{
    if (pexists(path))
    {
        printf("Removing %s\n", path);
        vigil_platform_remove(path, NULL);
    }
}

/* ── result helpers ──────────────────────────────────────────────── */

static vigil_editor_result_t result_ok(const char *msg)
{
    vigil_editor_result_t r = {VIGIL_STATUS_OK, {0}};
    snprintf(r.message, sizeof(r.message), "%s", msg);
    return r;
}

static vigil_editor_result_t result_err(const char *msg)
{
    vigil_editor_result_t r = {VIGIL_STATUS_INTERNAL, {0}};
    snprintf(r.message, sizeof(r.message), "%s", msg);
    return r;
}

